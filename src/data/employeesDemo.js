/**
 * Construit un jeu complet de soldes de congés à partir d'un objet partiel.
 * Les types non spécifiés reçoivent total=0.
 */
function buildLeaveBalances(overrides = {}) {
  return leaveTypesCatalog.map((name) => {
    const o = overrides[name] || {};
    const total = o.total ?? 0;
    const used = o.used ?? 0;
    return {
      name,
      total,
      used,
      remaining: Math.max(0, total - used),
    };
  });
}

